import assert from "node:assert/strict";
import { createRequire } from "node:module";
globalThis.satellite = createRequire(import.meta.url)("./satellite.min.js");
await import("./iss.js");
const { project, parseTLE, subpoint, groundTrack } = globalThis.ISS;
assert.deepEqual(project(-180,90,2560,720), {x:0,y:0});
assert.deepEqual(project(180,-90,2560,720), {x:2560,y:720});
const text = "ISS (ZARYA)\n1 25544U 98067A   26209.15252568  .00010831  00000+0  20282-3 0  9992\n2 25544  51.6320  97.3682 0007093 345.6120  14.4666 15.49220842578109";
const tle = parseTLE(text);
assert.ok(tle && tle.l1.startsWith("1 25544") && tle.l2.startsWith("2 25544"), "parseTLE");
assert.equal(parseTLE("garbage\nno tle here"), null, "parseTLE null on junk");
const rec = globalThis.satellite.twoline2satrec(tle.l1, tle.l2);
const p = subpoint(rec, new Date(Date.UTC(2026,6,28,12,0,0)));
assert.ok(Math.abs(p.lat-30.83)<1 && Math.abs(p.lon-121.46)<1, `subpoint ~30.8,121.5 got ${p.lat},${p.lon}`);
assert.ok(p.altKm>350 && p.altKm<450, "alt plausible");
const gt = groundTrack(rec, Date.UTC(2026,6,28,12,0,0), Date.UTC(2026,6,28,13,30,0), 60000);
assert.ok(gt.length>50 && gt.every(pt=>Math.abs(pt.lat)<=52.5), "track lat within inclination");
console.log("iss.test.mjs OK");
